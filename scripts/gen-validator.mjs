// Precompiles ai/import.schema.json into standalone validation code (no ajv runtime, and
// crucially no `new Function` — the extension's CSP has no 'unsafe-eval', so runtime schema
// compilation would throw in the background page). Output is generated, gitignored, and
// rebuilt by `npm run build` / `pretest`.
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { _ } from 'ajv/dist/compile/codegen/index.js';
import addFormats from 'ajv-formats';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(readFileSync(`${root}/ai/import.schema.json`, 'utf8'));

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  allowUnionTypes: true, // answerEntry.value / answerOverrides are string|number|boolean by design
  code: { source: true, formats: _`require("ajv-formats/dist/formats").fullFormats` },
});
addFormats(ajv);

const validate = ajv.compile(schema);
const source = standaloneCode.default(ajv, validate);

mkdirSync(`${root}/src/shared/schema`, { recursive: true });
writeFileSync(
  `${root}/src/shared/schema/validate-import.gen.cjs`,
  `// GENERATED by scripts/gen-validator.mjs — do not edit.\n${source}`,
);
console.log('generated src/shared/schema/validate-import.gen.cjs');
